public class ExersicesVariablesyConstantes {
    static void main(String[] args) {

        //1. Declara una variable de tipo String y asignale tu nombre

        String name = "Fabian";
        System.out.println(name);

        //2. Crea una variable de tipo int y asignale tu edad

        int age = 19;
        System.out.println(age);

        var edad = 19;
        System.out.println(edad);

        //3. Crea una variable double con tu altura en metros

        double altura = 1.75;
        System.out.println(altura);

        var heigth = 1.75;
        System.out.println(heigth);

        //4. Declara una variable de tipo boolean que indique si te gusta programar

        boolean teGustaProgramar = true;
        teGustaProgramar = false;
        System.out.println(teGustaProgramar);

        //5. Declara una constante con tu email

        final String email = "fabian@gmail.com";
        System.out.println(email);

        //6. Crea una variable de tipo char y guardale tu inicial

        char myInicial = 'F';
        System.out.println(myInicial);

        //7. Declara una variable de tipo String con tu localidad y acontinuacion cambia su valor y vuelve a imprimirla

        String mycity = "Santiago";
        System.out.println(mycity);

        mycity = "SantaCruz";
        System.out.println(mycity);

        //8. Crea una variable int llamada a. y otra b, e imprime la suma de ambas

        int a = 10;
        int b = 5;

        System.out.println(a + b);

        //9. Intenta declarar una variable sin incializarla y luego asignale un valor antes de imprimirla

        String lasName = "ArandiaVargas";
        System.out.println(lasName);

    }
}
